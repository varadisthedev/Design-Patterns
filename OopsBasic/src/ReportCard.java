// create  a POJO in java
class ReportCard {
    String name;
    int marks;

    // setter for name
    public void setName(String name) {
        this.name = name;
    }
    // setter for marks
    public void setMarks(int marks) {
        this.marks = marks;
    }


    // getter for marks and name
    public int getMarks() {
        return marks;
    }

    public String getName() {
        return name;
    }
}
